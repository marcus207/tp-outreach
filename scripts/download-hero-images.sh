#!/usr/bin/env bash
# Download high-quality 1200x628 hero images from Unsplash for all sectors.
# Replaces existing low-res hero images in data/hero/.
# Unsplash license: free for commercial use, no attribution required.

set -euo pipefail
HERO_DIR="$(cd "$(dirname "$0")/../data/hero" && pwd)"
UNSPLASH="https://images.unsplash.com/photo-"
PARAMS="?w=1200&h=628&fit=crop&crop=center&auto=format&q=85"
OK=0
FAIL=0

download() {
  local sector="$1" idx="$2" photo_id="$3"
  local outfile="${HERO_DIR}/${sector}_$(printf '%02d' "$idx").jpg"
  local url="${UNSPLASH}${photo_id}${PARAMS}"
  curl -sL -o "$outfile" "$url" 2>/dev/null
  local dims
  dims=$(identify "$outfile" 2>/dev/null | awk '{print $3}') || dims=""
  local w="${dims%%x*}"
  if [[ "$w" -ge 1100 ]] 2>/dev/null; then
    echo "  ✓ ${sector}_$(printf '%02d' "$idx").jpg (${dims})"
    OK=$((OK + 1))
  else
    echo "  ✗ ${sector}_$(printf '%02d' "$idx").jpg FAILED"
    rm -f "$outfile"
    FAIL=$((FAIL + 1))
  fi
}

